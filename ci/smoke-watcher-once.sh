#!/usr/bin/env bash
# Checks that the built image ships the bundled scripts and no dev
# dependencies, runs its watcher with --once against a generated fixture
# library and checks that it never deletes a derivative, then starts the web
# server on that library and checks that the removed image endpoints return
# 404, and that nothing under /assets/photos is served, legacy derivatives
# and original source files alike, directly or through /_next/image.
#
#   IMAGE=ghcr.io/keyurgolani/keyurgolani.photography:ci-smoke ci/smoke-watcher-once.sh
#
# $IMAGE must already exist locally, since nothing pulls here. The image
# generates the library itself with this checkout's
# test/fixtures/makeLibrary.ts, which its node runs with the types stripped,
# so the runner needs no Node and no fixture binaries are committed.
# WATCHER_CMD overrides the watcher command. Binds a random port on 127.0.0.1.
set -euo pipefail

cd "$(dirname "$0")/.."

IMAGE=${IMAGE:-ghcr.io/keyurgolani/keyurgolani.photography:ci-smoke}
WATCHER_CMD=${WATCHER_CMD:-node dist/scripts/imageWatcher.mjs}
read -r -a WATCHER <<<"$WATCHER_CMD"

TMP=$(mktemp -d)
LIB=$TMP/library
WEB=photography-smoke-watcher-$$
WEB_STARTED=false
# The body of /_next/image's 400 for a url images.localPatterns doesn't allow.
NOT_ALLOWED='"url" parameter is not allowed'
OUTPUTS=(
  thumbnails/%s.webp medium/%s.webp optimized/%s.webp
  thumbnails-avif/%s.avif medium-avif/%s.avif optimized-avif/%s.avif
  lqip/%s.txt
)

fail() {
  echo "::error::$1"
  exit 1
}

cleanup() {
  status=$?
  set +e
  if [ "$WEB_STARTED" = true ]; then
    if [ "$status" -ne 0 ]; then
      echo "Smoke test failed. Web container logs:"
      docker logs "$WEB"
    fi
    docker rm -f "$WEB" >/dev/null
  fi
  # The watcher creates the derivative folders as uid 1001. Remove them with
  # the image under test, so cleanup never pulls anything.
  docker run --rm --pull never --user 0 --entrypoint rm -v "$TMP:/t" "$IMAGE" -rf /t/library
  rm -rf "$TMP"
  exit "$status"
}
trap cleanup EXIT

run_once() {
  docker run --rm --pull never -e PHOTOGRAPHY_LIBRARY_DIR=/library -v "$LIB:/library" "$IMAGE" "${WATCHER[@]}" --once
}

# Fails unless all seven derivatives of <base> exist and are non-empty.
require_outputs() {
  local base=$1 context=$2 pattern output
  for pattern in "${OUTPUTS[@]}"; do
    # shellcheck disable=SC2059 # the pattern is ours, with one %s
    output=$(printf "$pattern" "$base")
    [ -s "$LIB/$output" ] || fail "$context: $output is missing or empty."
  done
}

# 0. The image runs the watcher and the CLIs from their bundles, and carries
#    none of package.json's devDependencies, tsx among them, and none of the
#    sources the bundles are built from.
problems=$(docker run --rm --pull never "$IMAGE" node -e '
  const fs = require("fs");
  const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
  const problems = [];
  for (const name of new Set(["tsx", ...Object.keys(pkg.devDependencies || {})])) {
    if (fs.existsSync("node_modules/" + name)) problems.push("node_modules/" + name);
  }
  for (const source of ["scripts", "utils", "lib", "tsconfig.json"]) {
    if (fs.existsSync(source)) problems.push(source);
  }
  for (const script of ["imageWatcher", "photos", "watcherHealth"]) {
    if (!fs.existsSync("dist/scripts/" + script + ".mjs")) problems.push("no dist/scripts/" + script + ".mjs");
  }
  console.log(problems.join(", "));
') || fail "Listing what $IMAGE ships failed."
[ -z "$problems" ] || fail "The image should ship only the bundled scripts and runtime packages, but has: $problems."
echo "The image ships dist/scripts and no dev dependencies, tsx, or script sources."

# 1. A library the container's uid 1001 can write into, generated by the image
#    under test with this checkout's fixtures mounted read-only.
mkdir "$LIB"
chmod 777 "$LIB"
docker run --rm --pull never -v "$PWD/test/fixtures:/app/test/fixtures:ro" -v "$LIB:/library" \
  "$IMAGE" node test/fixtures/makeLibrary.ts /library || fail "Generating the fixture library in $IMAGE failed."

# 2. --once writes all seven derivatives for each fixture.
echo "Running ${WATCHER_CMD} --once in $IMAGE."
run_once || fail "The first --once run exited non-zero."
for base in landscape portrait square; do
  require_outputs "$base" "After the first --once run"
done
count=$(find "$LIB/optimized" -maxdepth 1 -name '*.webp' | wc -l | tr -d ' ')
[ "$count" -eq 3 ] || fail "Expected 3 optimized/*.webp after the first --once run, found $count."
echo "--once wrote all seven derivatives for each fixture."

# 3. With a source gone, another --once run keeps its derivatives.
# The image wrote it as uid 1001, so force the removal and check it took.
rm -f "$LIB/landscape.jpg"
[ ! -e "$LIB/landscape.jpg" ] || fail "Could not remove landscape.jpg from the fixture library."
run_once || fail "The second --once run exited non-zero."
require_outputs landscape "After removing landscape.jpg"
echo "--once kept landscape's derivatives after landscape.jpg was removed."

# 4. A missing library root exits 1 instead of being recreated.
set +e
docker run --rm --pull never -e PHOTOGRAPHY_LIBRARY_DIR=/tmp/missing-library "$IMAGE" "${WATCHER[@]}" --once
code=$?
set -e
[ "$code" -eq 1 ] || fail "--once exited $code on a missing library root, expected 1."
echo "--once exited 1 on a missing library root."

# 5. The web server, with the library at its default path. Next serves only
#    public/ files present at startup, so it starts after the derivatives exist.
docker run -d --pull never --name "$WEB" -p 127.0.0.1::3000 -v "$LIB:/app/public/assets/photos" "$IMAGE" >/dev/null
WEB_STARTED=true
address=$(docker port "$WEB" 3000/tcp)
address=${address%%$'\n'*}
BASE_URL=http://127.0.0.1:${address##*:}

deadline=$((SECONDS + 60))
until [ "$(curl -s --max-time 5 -o /dev/null -w '%{http_code}' "$BASE_URL/")" = 200 ]; do
  [ "$SECONDS" -lt "$deadline" ] || fail "GET / did not return 200 within 60s."
  sleep 1
done
echo "GET / returned 200."

code=$(curl -sS --max-time 30 -o /dev/null -w '%{http_code}' -X POST "$BASE_URL/api/photos/optimize") ||
  fail "POST /api/photos/optimize failed."
[ "$code" = 404 ] || fail "POST /api/photos/optimize returned $code, expected 404."
code=$(curl -sS --max-time 30 -o /dev/null -w '%{http_code}' "$BASE_URL/api/image?src=portrait.png") ||
  fail "GET /api/image failed."
[ "$code" = 404 ] || fail "GET /api/image?src=portrait.png returned $code, expected 404."
echo "The removed image endpoints return 404."

# 6. Nothing under /assets/photos serves, the derivatives the watcher just
#    wrote included: every one 404s with a no-store response, and
#    /_next/image refuses each with 400, for the reason that images.localPatterns
#    doesn't allow it. Photos serve only from /media.
for asset in optimized/portrait.webp thumbnails-avif/square.avif lqip/landscape.txt portrait.png square.webp portrait%2Epng; do
  code=$(curl -sS --max-time 30 -D "$TMP/headers.txt" -o /dev/null -w '%{http_code}' "$BASE_URL/assets/photos/$asset") ||
    fail "GET /assets/photos/$asset failed."
  [ "$code" = 404 ] || fail "GET /assets/photos/$asset returned $code, expected 404."
  tr -d '\r' <"$TMP/headers.txt" | grep -qix 'cache-control: no-store' || fail "The 404 for /assets/photos/$asset did not send Cache-Control: no-store."
done
for url in %2Fassets%2Fphotos%2Foptimized%2Fportrait.webp %2Fassets%2Fphotos%2Fthumbnails-avif%2Fsquare.avif %2Fassets%2Fphotos%2Fportrait.png; do
  code=$(curl -sS --max-time 30 -o "$TMP/image-error.txt" -w '%{http_code}' "$BASE_URL/_next/image?url=$url&w=400&q=75") ||
    fail "GET /_next/image?url=$url failed."
  [ "$code" = 400 ] || fail "GET /_next/image?url=$url returned $code, expected 400."
  [ "$(cat "$TMP/image-error.txt")" = "$NOT_ALLOWED" ] ||
    fail "GET /_next/image?url=$url answered 400 with '$(cat "$TMP/image-error.txt")', expected '$NOT_ALLOWED'."
done
echo "Legacy derivatives and originals return 404, and /_next/image refuses both with 400."
